export function findFoodById(id: string): FoodItem | undefined {
  return FOOD_DATABASE.find((item) => item.id === id);
}

export function searchFoodsByQuery(query: string): FoodItem[] {
  const q = query.trim().toLowerCase();
  if (!q) return FOOD_DATABASE;
  return FOOD_DATABASE.filter(
    (item) =>
      item.nome.toLowerCase().includes(q) ||
      item.id.toLowerCase().includes(q) ||
      item.apelidos.some((ap) => ap.toLowerCase().includes(q))
  );
}

export function matchFoodFromNaturalName(name: string): FoodItem | undefined {
  const normalized = name.trim().toLowerCase();
  if (!normalized) return undefined;
  return FOOD_DATABASE.find(
    (item) =>
      item.id === normalized ||
      item.nome.toLowerCase() === normalized ||
      item.apelidos.some((ap) => ap.toLowerCase() === normalized) ||
      item.nome.toLowerCase().includes(normalized) ||
      item.apelidos.some((ap) => normalized.includes(ap.toLowerCase()))
  );
}
